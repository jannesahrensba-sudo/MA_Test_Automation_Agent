'use strict';
/**
 * Bundles the browser build of the mock service (tools/hosted/browser/mockserver-entry.js) with esbuild.
 * Output: <outDir>/mockserver.js (IIFE, no Node.js built-ins).
 *
 * Usage: node tools/hosted/build-mockserver.js [outDir]
 */
const fs = require('fs');
const path = require('path');
const esbuild = require('esbuild');

const ROOT = path.join(__dirname, '../..');
const DATA_DIR = path.join(ROOT, 'webapp/localService/mainService/data');
const GENERATED = path.join(__dirname, 'browser/generated');
const SHIMS = path.join(__dirname, 'browser/shims');

async function build(outDir = path.join(ROOT, 'dist-hosted')) {
    // generated module: metadata + all mock data files + data contributors (same files as ui5 serve)
    fs.mkdirSync(GENERATED, { recursive: true });
    const entries = fs.readdirSync(DATA_DIR);
    const rel = (file) => path.relative(GENERATED, path.join(DATA_DIR, file)).replace(/\\/g, '/');
    const json = entries.filter((f) => f.endsWith('.json')).map((f) => `        ${JSON.stringify(f.replace(/\.json$/, ''))}: require(${JSON.stringify(rel(f))})`);
    const js = entries.filter((f) => f.endsWith('.js')).map((f) => `        ${JSON.stringify(f.replace(/\.js$/, ''))}: require(${JSON.stringify(rel(f))})`);
    const metadataRel = path.relative(GENERATED, path.join(ROOT, 'webapp/localService/mainService/metadata.xml')).replace(/\\/g, '/');
    fs.writeFileSync(
        path.join(GENERATED, 'mockdata.js'),
        `'use strict';\n// generated by tools/hosted/build-mockserver.js — do not edit\nmodule.exports = {\n    metadata: require(${JSON.stringify(metadataRel)}),\n    json: {\n${json.join(',\n')}\n    },\n    js: {\n${js.join(',\n')}\n    }\n};\n`
    );

    const shim = (name) => path.join(SHIMS, `${name}.js`);
    fs.mkdirSync(outDir, { recursive: true });
    const result = await esbuild.build({
        entryPoints: [path.join(__dirname, 'browser/mockserver-entry.js')],
        outfile: path.join(outDir, 'mockserver.js'),
        bundle: true,
        platform: 'browser',
        format: 'iife',
        target: ['es2020'],
        minify: true,
        legalComments: 'eof',
        loader: { '.xml': 'text' },
        define: { 'process.env.NODE_ENV': '"production"', __dirname: '"/"', global: 'globalThis' },
        inject: [],
        alias: {
            path: shim('path'),
            'path/posix': shim('path'),
            util: shim('util'),
            url: shim('url'),
            process: shim('process'),
            http: shim('http'),
            stream: shim('empty'),
            string_decoder: shim('empty'),
            fs: shim('empty'),
            'graceful-fs': shim('empty'),
            chokidar: shim('empty'),
            zlib: shim('empty'),
            etag: shim('empty'),
            'body-parser': shim('empty'),
            router: shim('empty'),
            timers: shim('empty'),
            buffer: shim('empty')
        },
        banner: { js: '/* Service-to-Cash Test Automation Assistant — in-browser OData V4 mock service (MOCK). Includes @sap-ux/fe-mockserver-core (Apache-2.0). */' },
        metafile: true,
        logLevel: 'warning'
    });
    const bytes = fs.statSync(path.join(outDir, 'mockserver.js')).size;
    console.log(`mockserver.js: ${(bytes / 1024).toFixed(0)} KB (${Object.keys(result.metafile.inputs).length} input files)`);
    return result;
}

if (require.main === module) {
    build(process.argv[2] && path.resolve(process.argv[2])).catch((error) => {
        console.error(error);
        process.exit(1);
    });
}

module.exports = { build };
